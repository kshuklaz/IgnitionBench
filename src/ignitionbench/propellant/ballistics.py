"""Internal ballistics: Kn ratio and steady-state chamber pressure.

Steady state balances mass generated by the burning surface against mass
leaving through the throat:

    ρ · Ab · r(P) = P · At / c*      →      P = Kn · ρ · r(P) · c*

where Kn = Ab / At. With Vieille's law r = a·Pⁿ this has a closed form for a
single segment, but the KN* propellants use piecewise fits, so we solve the
fixed point numerically over the validated pressure range.
"""

from __future__ import annotations

from scipy.optimize import brentq

from .database import Propellant

# Below ~2:1 the port chokes the flow and erosive burning invalidates the
# steady-state model (openMotor warns at the same threshold).
MIN_PORT_TO_THROAT = 2.0


def kn(burning_area: float, throat_area: float) -> float:
    """Kn ratio: burning surface area / nozzle throat area."""
    if throat_area <= 0:
        raise ValueError("throat_area must be positive")
    return burning_area / throat_area


def kn_for_pressure(propellant: Propellant, pressure: float) -> float:
    """The Kn that produces a given steady-state chamber pressure (Pa).

    Useful in reverse: given a casing's safe working pressure, this is the
    maximum Kn the design should reach at any point in the burn.
    """
    rate = propellant.burn_rate(pressure)  # validates the pressure range
    return pressure / (propellant.density * rate * propellant.c_star)


def steady_state_pressure(propellant: Propellant, kn_ratio: float) -> float:
    """Steady-state chamber pressure (Pa) for a Kn ratio.

    Raises ValueError when the equilibrium falls outside the propellant's
    validated burn-rate data — too high a Kn is a genuine overpressure
    hazard, not just a modelling gap.
    """
    if kn_ratio <= 0:
        raise ValueError("kn_ratio must be positive")

    def residual(pressure: float) -> float:
        rate = propellant.burn_rate(pressure)
        return pressure - kn_ratio * propellant.density * rate * propellant.c_star

    p_lo, p_hi = propellant.min_pressure, propellant.max_pressure
    if residual(p_hi) < 0:
        raise ValueError(
            f"Kn = {kn_ratio:.0f} drives {propellant.name} above its validated "
            f"maximum of {p_hi / 1e6:.2f} MPa — overpressure risk. Reduce Kn "
            "(larger throat or less burning surface)."
        )
    if residual(p_lo) > 0:
        raise ValueError(
            f"Kn = {kn_ratio:.0f} cannot sustain {propellant.name}'s minimum "
            f"validated pressure of {p_lo / 1e6:.2f} MPa — the motor would "
            "likely not reach stable combustion. Increase Kn."
        )
    return brentq(residual, p_lo, p_hi)


def port_to_throat(port_area: float, throat_area: float) -> float:
    """Port-to-throat area ratio; below MIN_PORT_TO_THROAT is a design warning."""
    if throat_area <= 0:
        raise ValueError("throat_area must be positive")
    return port_area / throat_area
